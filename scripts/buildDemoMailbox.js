// buildDemoMailbox.js
// Builds 50 FICTIONAL demo emails (21 phishing, 9 suspicious, 20 normal) and writes them
// into seeder/DemoEmails.gs, so the seeder can import them into the TEST Gmail account.
// Run:  node scripts/buildDemoMailbox.js
//
// All phishing domains end with ".example" (a name reserved for examples: it can
// never belong to anyone), and their network data is in fixtures/intel/.

const fs = require("fs");
const path = require("path");

// Gmail's own verdict line. "pass" for normal mail, "fail" / "softfail" for forged mail.
function authLine(result, mailFrom, fromDomain) {
  if (result === "pass") {
    return "mx.google.com; dkim=pass header.i=@" + fromDomain + "; spf=pass smtp.mailfrom=" + mailFrom + "; dmarc=pass header.from=" + fromDomain;
  }
  return "mx.google.com; spf=" + result + " smtp.mailfrom=" + mailFrom + "; dkim=none; dmarc=fail header.from=" + fromDomain;
}

function headerLines(e, index) {
  const fromDomain = e.from.split("@")[1];
  const mailFrom = (e.returnPath || e.from).split("@")[1];
  const lines = [
    'From: "' + e.name + '" <' + e.from + ">",
    "To: demo-user@example.com",
    "Subject: " + e.subject,
    "Date: " + new Date(e.date).toUTCString().replace("GMT", "+0000"),
    "Message-ID: <demo-" + index + "@inbox-detective.example>",
    "X-Inbox-Detective-Demo: fictional demo email",
  ];
  // auth "none": no Authentication-Results at all (Gmail could not confirm the sender).
  if (e.auth !== "none") lines.push("Authentication-Results: " + authLine(e.auth, mailFrom, fromDomain));
  if (e.replyTo) lines.push("Reply-To: <" + e.replyTo + ">");
  if (e.returnPath) lines.push("Return-Path: <" + e.returnPath + ">");
  lines.push("MIME-Version: 1.0");
  return lines;
}

// A harmless file with a tricky NAME (the attachment check only reads the name).
// We use ".html" because Gmail refuses .exe/.js attachments; attackers really use
// HTML attachments that open a fake login page ("HTML smuggling").
function attachmentPart(fileName) {
  const content = Buffer.from("<p>Harmless demo file. It does nothing.</p>").toString("base64");
  return ["--demo-boundary", "Content-Type: text/html; name=\"" + fileName + "\"",
    "Content-Disposition: attachment; filename=\"" + fileName + "\"", "Content-Transfer-Encoding: base64", "", content];
}

function makeEml(e, index) {
  const lines = headerLines(e, index);
  const html = "<html><body>" + e.body + "</body></html>";
  if (!e.attachment) {
    return lines.concat(["Content-Type: text/html; charset=utf-8", "", html]).join("\r\n");
  }
  return lines.concat(['Content-Type: multipart/mixed; boundary="demo-boundary"', "",
    "--demo-boundary", "Content-Type: text/html; charset=utf-8", "", html,
    ...attachmentPart(e.attachment), "--demo-boundary--"]).join("\r\n");
}

const EMAILS = require("./demoMailboxData");

function main() {
  const raws = EMAILS.map((e, i) => makeEml(e, i + 1));
  const out = "// DemoEmails.gs\n// GENERATED by scripts/buildDemoMailbox.js - do not edit by hand.\n" +
    "// " + raws.length + " fictional demo emails (raw .eml text) for the test mailbox.\n\n" +
    "const DEMO_EMAILS = " + JSON.stringify(raws, null, 1) + ";\n";
  fs.writeFileSync(path.join(__dirname, "..", "seeder", "DemoEmails.gs"), out);
  console.log("Wrote " + raws.length + " emails to seeder/DemoEmails.gs");
}

if (require.main === module) main();

module.exports = { makeEml };
